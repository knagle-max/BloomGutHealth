test("23andMe parser validates GRCh37 and forward coordinates, minimizes retained data and handles no-calls", () => {
  const g = parse23andMe(raw, date);
  assert.equal(g.scannedVariants, 3);
  assert.equal(g.calls.length, 2);
  assert.equal(g.calls[1].genotype, "GG");
  assert.ok(!JSON.stringify(g).includes("rs99999"));
  assert.equal(
    parse23andMe(raw.replace("\tAG", "\t--"), date).calls[0].genotype,
    "--",
  );
  for (const bad of [
    raw.replace("build 37", "build 38"),
    raw.replace("11856378", "11856379"),
    raw.replace("\tAG", "\tCT"),
    raw + "\nrs1801133 1 11856378 AA",
    raw + "\n# negative strand",
  ]) {
    assert.throws(() => parse23andMe(bad, date));
  }
  assert.equal(
    geneticImportSchema.safeParse({ ...g, consent: false }).success,
    false,
  );
  assert.equal(
    geneticImportSchema.safeParse({ ...g, rawFile: raw }).success,
    false,
  );
});
test("laboratory schema rejects wrong units, impossible ranges and future timestamps; equivalent units normalize", () => {
  assert.equal(labSchema.safeParse({ ...lab(), unit: "ng/mL" }).success, false);
  assert.equal(
    labSchema.safeParse({ ...lab(), referenceLow: 4, referenceHigh: 3 })
      .success,
    false,
  );
  assert.equal(labSchema.safeParse({ ...lab(), value: NaN }).success, false);
  assert.equal(
    labSchema.safeParse({
      ...lab(),
      measuredAt: new Date(now + 86400000).toISOString(),
    }).success,
    false,
  );
  assert.ok(
    Math.abs(canonicalLab(lab({ value: 154.68, unit: "mg/dL" })).value - 4) <
      0.001,
  );
  assert.equal(
    canonicalLab(lab({ marker: "apob", value: 120, unit: "mg/dL" })).value,
    1.2,
  );
  assert.equal(
    canonicalLab(lab({ marker: "vitamin_d", value: 20, unit: "ng/mL" })).value,
    50,
  );
});
test("measured flags outweigh genetics; stale labs and no-calls cannot create false deficiencies", () => {
  const genetic = record("g", "genetics", parse23andMe(raw, date));
  const base = buildPrecisionReport(
    [genetic],
    context,
    defaultPreferences,
    null,
    now,
  );
  assert.equal(base.supplements.length, 0);
  assert.equal(base.labs.length, 0);
  assert.equal(base.microbiome.measuredMetabolites.length, 0);
  const active = buildPrecisionReport(
    [genetic, record("ldl", "lab", lab())],
    context,
    defaultPreferences,
    null,
    now,
  );
  assert.ok(active.recommendations[0].priority >= 40);
  assert.ok(active.recommendations[0].matchedRecordIds.includes("ldl"));
  const old = buildPrecisionReport(
    [
      record(
        "old",
        "lab",
        lab({ measuredAt: new Date(now - 200 * 86400000).toISOString() }),
      ),
    ],
    context,
    defaultPreferences,
    null,
    now,
  );
  assert.equal(old.labs[0].stale, true);
  assert.ok(
    old.recommendations.every((r) => !r.matchedRecordIds.includes("old")),
  );
  const noCall = buildPrecisionReport(
    [record("nc", "genetics", parse23andMe(raw.replace("\tAG", "\t--"), date))],
    context,
    defaultPreferences,
    null,
    now,
  );
  assert.ok(
    noCall.recommendations.every(
      (r) => !r.reasons.some((s) => s.includes("MTHFR")),
    ),
  );
  assert.equal(
    active.goals.find((g) => g.goal === "My own research goal")?.mapping,
    "Needs a more specific food or health target",
  );
});
test("food, meal and supplement outputs honor preferences, avoid genetic dairy bans and enforce safety context", () => {
  const prefs = preferenceSchema.parse({
    dietaryPattern: "vegan",
    exclusions: ["nuts", "alliums"],
    dislikes: ["tofu"],
    goals: ["butyrate", "diversity"],
  });
  const r = buildPrecisionReport(
    [
      record(
        "b12",
        "lab",
        lab({
          marker: "b12",
          value: 100,
          unit: "pmol/L",
          referenceLow: 150,
          referenceHigh: 700,
        }),
      ),
    ],
    contextSchema.parse({ ageGroup: "adult" }),
    prefs,
    null,
    now,
  );
  assert.ok(r.recommendations.length);
  assert.ok(
    r.recommendations.every((m) =>
      m.ingredients.every(
        (i) =>
          !i.tags.some((t) =>
            ["meat", "seafood", "dairy", "eggs", "nuts", "alliums"].includes(t),
          ) && !/tofu/i.test(i.name),
      ),
    ),
  );
  assert.ok(!r.foods.some((f) => f.id === "walnuts" || f.id === "yogurt"));
  assert.equal(r.supplements[0].status, "blocked pending safety review");
  assert.equal(r.supplements[0].dose, null);
  const tolerance = buildPrecisionReport(
    [record("g", "genetics", parse23andMe(raw, date))],
    context,
    preferenceSchema.parse({ goals: ["diversity"] }),
    null,
    now,
  );
  assert.ok(tolerance.recommendations.some((m) => m.tolerance));
  assert.equal(
    buildPrecisionReport(
      [],
      contextSchema.parse({ ageGroup: "under18" }),
      prefs,
      null,
      now,
    ).recommendations.length,
    0,
  );
});
